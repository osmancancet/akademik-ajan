"""Render eval/llm/REPORT.md from numbers.json. Every number in the report comes from there.

Usage:  python eval/llm/report.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
MODELS = ["haiku", "sonnet", "opus"]


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def ci(c: list[float] | None) -> str:
    return "n/a" if not c else f"{100 * c[0]:.1f}–{100 * c[1]:.1f}%"


def main() -> None:
    n = json.loads((HERE / "numbers.json").read_text(encoding="utf-8"))
    rq, adj, err = n["requests"], n["adjudication"], n["errors"]
    tr_lists = sum(rq[f"{m}_tr"].get("complied", 0) for m in MODELS)
    tr_partial = sum(rq[f"{m}_tr"].get("partial", 0) for m in MODELS)
    tr_total = sum(sum(rq[f"{m}_tr"].values()) for m in MODELS)
    en_total = sum(sum(rq[f"{m}_en"].values()) for m in MODELS)
    en_lists = sum(rq[f"{m}_en"].get("complied", 0) for m in MODELS)
    tr_refs = sum(n["references_by_model_lang"][f"{m}_tr"] for m in MODELS)
    v0s, v0l = n["verifier_v010_strict"], n["verifier_v010_lenient"]
    v1s, v1l = n["verifier_current_strict"], n["verifier_current_lenient"]

    out = []
    w = out.append
    w("# References written by language models: run A (agent context)")
    w("")
    w("_Generated by `eval/llm/report.py` from `numbers.json`. Do not edit numbers by hand._")
    w("")
    w("## Setup")
    w("")
    w(f"Three models ({', '.join(n['served_models'])}) each answered 12 closed-book requests for 10 "
      "references (6 international topics prompted in English, 6 Turkish-literature topics prompted "
      "in Turkish), with no tool use. The models ran as Claude Code sub-agents whose context held a "
      "user profile and a project rule against bibliographic data from memory; see "
      "[ADR-0003](../../docs/adr/0003-llm-reference-study.md). Results describe that agent context, "
      "not the models in isolation.")
    w("")
    w(f"Ground truth: blind web adjudication of {adj['sample_size']} references, namely all "
      f"{adj['flagged_in_sample']} that verifier v0.1.0 did not mark `verified` and a random "
      f"{adj['verified_sampled']} of its {adj['verified_population']} verified ones. Adjudicators saw "
      "only the citation text.")
    w("")
    w("## 1. Did the model produce a list?")
    w("")
    w("| Model | English topics | Turkish topics |")
    w("|---|---|---|")
    for m in MODELS:
        fmt = lambda d: ", ".join(f"{k} {v}" for k, v in sorted(d.items()))  # noqa: E731
        w(f"| {m} | {fmt(rq[f'{m}_en'])} | {fmt(rq[f'{m}_tr'])} |")
    w("")
    w(f"All {en_lists} of {en_total} English requests returned a full list. Of {tr_total} Turkish "
      f"requests, {tr_lists} returned a full list and {tr_partial} a partial one; the rest declined, "
      f"citing uncertainty and, in many replies, the project rule. Only {tr_refs} Turkish-topic "
      "references were produced, so the analysis below concerns the English topics.")
    w("")
    w("## 2. How accurate were the references?")
    w("")
    w(f"Adjudicators found **{err['fabricated_count']} non-existent works** and "
      f"**{err['count']} references with wrong details** among {n['references_total']} references. "
      f"Every sampled verified reference was correct ({adj['verified_sampled'] - adj['verified_sampled_wrong']}/"
      f"{adj['verified_sampled']}; 95% CI for the error rate among verified references: "
      f"{ci(adj['verified_error_ci95'])}).")
    w("")
    w("| Model | References | With wrong details | Rate (95% CI) |")
    w("|---|---|---|---|")
    for m in MODELS:
        r = err["rate_by_model"][m]
        w(f"| {m} | {r['n']} | {r['k']} | {pct(r['k'] / r['n'] if r['n'] else None)} ({ci(r['ci95'])}) |")
    w("")
    fields = ", ".join(f"{k} {v}" for k, v in sorted(err["wrong_fields"].items(), key=lambda t: -t[1]))
    w(f"Wrong fields: {fields}. The typical error is a real paper with a DOI that resolves to a "
      "different paper; a reader who clicks the DOI lands on the wrong work.")
    w("")
    w("## 3. How well did the verifier separate them?")
    w("")
    w("Strict: only `verified` passes. Lenient: `partial_match` (e.g. year off by one) also passes.")
    w("")
    w("| Verifier | Rule | Errors caught | False alarms on correct references (95% CI) |")
    w("|---|---|---|---|")
    for label, s, l in (("v0.1.0 (blind)", v0s, v0l), ("v0.2.0 (tuned on this sample)", v1s, v1l)):
        for rule, v in (("strict", s), ("lenient", l)):
            w(f"| {label} | {rule} | {v['tp']}/{v['tp'] + v['fn']} | {v['fp']}/{v['fp'] + v['tn']} "
              f"= {pct(v['false_alarm_rate'])} ({ci(v['false_alarm_ci95'])}) |")
    w("")
    w(f"Under the strict rule v0.1.0 flagged every erroneous reference, and {v0s['mismatch_true_errors']} "
      f"of its {v0s['mismatch_flags']} `mismatch` verdicts were real errors. The cost is false alarms: "
      f"{v0s['fp']} correct references were flagged, {v0s['false_alarms_without_doi']} of them cited "
      f"without a DOI and {v0s['false_alarms_openalex_unchecked']} checked while OpenAlex was "
      f"unavailable (keyless daily quota). After the v0.2.0 fixes, {n['false_alarms_current_strict_conference']} "
      f"of the {v1s['fp']} remaining false alarms are conference papers (NeurIPS, ICLR, USENIX Security and "
      "similar), which Crossref largely does not index. The v0.2.0 fix for online-first versus print years removed the "
      f"one false `mismatch`; v0.2.0 figures are optimistic because the fix came from this sample.")
    w("")
    oa = n.get("openalex_recheck")
    if oa:
        w("### With OpenAlex reachable")
        w("")
        w(f"The {oa['rechecked']} strict false alarms of v0.2.0 were re-verified after OpenAlex's daily quota "
          f"reset (OpenAlex unreachable for {oa['openalex_unchecked_after']} of them). Hard alarms "
          f"(`not_found`, `doi_not_found`, `mismatch`) fell from {oa['strong_alarms_before']} to "
          f"{oa['strong_alarms_after']}, and OpenAlex supplied the match for {oa['matched_via_openalex']} "
          f"references. Strict false alarms fell only from {oa['rechecked']} to "
          f"{oa['strict_false_alarms_after']}: most recovered references became `possible_match`. In the three "
          "cases inspected, OpenAlex returned the arXiv preprint dated a year before the conference version "
          "the model cited, so only the year check warned. "
          "The flag is softer (the record is shown for confirmation), but it is still a flag. This was "
          "observed on the development sample and is left unfixed here so that run B tests it.")
        w("")
    w("## Limitations")
    w("")
    w("- Agent context, not isolated models: the project rule and user profile were visible.")
    w("- One sample per model and topic; temperature not controlled.")
    w(f"- {err['count']} errors is a small count; per-model rates have wide intervals.")
    ec = n.get("errors_confirmed_against_crossref", {"confirmed": 0, "checked": 0})
    w("- Adjudication was done by language-model agents with web access, not by people. The "
      f"{ec['checked']} error labels were re-checked against the Crossref record of the cited DOI "
      f"({ec['confirmed']} confirmed); the `correct` labels were not re-checked by a person.")
    w("")
    w("## Next")
    w("")
    w("Run B (`generate.py`): direct API calls without system prompt, 5 repeats, the same protocol, "
      "scored by the frozen v0.2.0 verifier with OpenAlex available. Run B is the unbiased test.")
    (HERE / "REPORT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
